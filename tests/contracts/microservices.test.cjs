const { spawnSync } = require('node:child_process');
const path = require('node:path');
const { loader } = require('../sprint1/helpers.cjs');
const workspace = path.resolve(__dirname, '../../..');
function backendFetch(repo, python) {
  const failures = [];
  const responses = [];
  const transport = async (url, options = {}) => {
    const parsed = new URL(url);
    const child = spawnSync(python, ['-B', path.join(__dirname, 'backend_bridge.py'), path.join(workspace, 'backend_admission', repo)], {
      input: JSON.stringify({ method: options.method || 'GET', path: parsed.pathname + parsed.search,
        body: options.body ? JSON.parse(options.body) : undefined, headers: options.headers }),
      encoding: 'utf8', timeout: 30000, windowsHide: true,
      env: { ...process.env, PYTHONIOENCODING: 'utf-8', PYTHONPATH: process.env.AI_TEST_PYTHONPATH || path.join(workspace, 'frontend_admission/.test-tools') },
    });
    // Bridge errors must fail, never be mistaken for expected service failure/fallback.
    if (child.status !== 0) {
      const message = `Bridge failed: ${child.error?.message || child.stderr}`;
      failures.push(message);
      throw Error(message);
    }
    const result = JSON.parse(child.stdout);
    responses.push(result);
    return { ok: result.status >= 200 && result.status < 300, status: result.status, json: async () => result.body };
  };
  transport.verify = () => {
    assert.deepEqual(failures, [], 'Backend bridge must execute successfully');
    assert.ok(responses.length, 'At least one actual FastAPI response is required');
    return responses.at(-1);
  };
  return transport;
}
const aiFetch = backendFetch('backend_ai_ml_latest', process.env.AI_TEST_PYTHON || 'python');
